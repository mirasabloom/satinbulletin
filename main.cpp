#include <string>
#include <vector>

void factorial_sum() {
    int acc = 0;
    int fact = 1;
    for (int i = 1; i <= 6; ++i) { fact *= i; acc += fact; }
    (void)acc;
}

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void char_frequency() {
    std::string text = "banana";
    int count = 0;
    for (std::size_t i = 0; i < text.size(); ++i) {
        if (text[i] == 'a') count += 1;
    }
    (void)count;
}

void midpoint_value() {
    int a = 14, b = 30;
    int mid = (a + b) / 2;
    (void)mid;
}

extern "C" int mellow_fjord();
extern "C" void calm_spruce();
extern "C" void clever_hollow();

int main() {
    factorial_sum();
    text_contains();
    char_frequency();
    midpoint_value();
    calm_spruce();
    clever_hollow();
    return mellow_fjord();
}
